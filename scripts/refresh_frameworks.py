"""Rebuild the framework indexes in src/tra_core/data from their published sources.

The agent checks every ATT&CK, ATLAS and ISM ID it writes against these
indexes, so refresh them when a new release comes out, then run the tests:
a mapping that cites a withdrawn or renumbered ID fails them.

Download the sources first (any machine with internet access):

    curl -LO https://raw.githubusercontent.com/mitre-attack/attack-stix-data/master/enterprise-attack/enterprise-attack.json
    curl -LO https://raw.githubusercontent.com/mitre-atlas/atlas-data/main/dist/ATLAS.yaml
    git clone --depth 1 https://github.com/AustralianCyberSecurityCentre/ism-oscal

then:

    python scripts/refresh_frameworks.py --attack enterprise-attack.json --atlas ATLAS.yaml --ism ism-oscal
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import yaml

DATA = Path(__file__).resolve().parents[1] / "src" / "tra_core" / "data"
HEADER = "# Generated by scripts/refresh_frameworks.py from the published source. Do not edit by hand.\n"


def attack(path: Path) -> dict:
    bundle = json.loads(path.read_text(encoding="utf-8"))
    version, techniques = "unknown", {}
    for o in bundle["objects"]:
        if o["type"] == "x-mitre-collection":
            version = o.get("x_mitre_version", version)
        if o["type"] != "attack-pattern" or o.get("revoked") or o.get("x_mitre_deprecated"):
            continue
        ref = next((e for e in o.get("external_references", []) if e.get("source_name") == "mitre-attack"), None)
        if ref:
            techniques[ref["external_id"]] = {
                "name": o["name"],
                "tactics": [p["phase_name"] for p in o.get("kill_chain_phases", [])],
            }
    return {"framework": "MITRE ATT&CK Enterprise", "version": str(version), "techniques": dict(sorted(techniques.items()))}


def atlas(path: Path) -> dict:
    raw = yaml.safe_load(path.read_text(encoding="utf-8"))
    techniques = {}
    for matrix in raw["matrices"]:
        for t in matrix.get("techniques", []):
            techniques[t["id"]] = {"name": t["name"]}
    return {"framework": "MITRE ATLAS", "version": str(raw.get("version")), "techniques": dict(sorted(techniques.items()))}


def _ids(group: dict, out: set[str]) -> set[str]:
    for c in group.get("controls", []):
        out.add(c["id"])
        _ids(c, out)
    for g in group.get("groups", []):
        _ids(g, out)
    return out


def ism(folder: Path) -> dict:
    catalog = json.loads((folder / "ISM_catalog.json").read_text(encoding="utf-8"))["catalog"]
    baseline = json.loads(
        (folder / "ISM_OFFICIAL_SENSITIVE-baseline-resolved-profile_catalog.json").read_text(encoding="utf-8")
    )["catalog"]
    in_baseline = _ids(baseline, set())
    controls = {}

    def walk(group: dict, path: list[str]) -> None:
        for c in group.get("controls", []):
            if c["id"] in in_baseline and c["id"].split("-")[1].isdigit():
                statement = " ".join(p.get("prose", "") for p in c.get("parts", []) if p.get("name") == "statement")
                entry = {"guideline": path[0] if path else "", "section": path[-1] if path else "", "statement": statement}
                e8 = [p["value"] for p in c.get("props", []) if p["name"] == "essential-eight-applicability"]
                if e8:
                    entry["essential_eight"] = e8
                controls[c["id"].upper()] = entry
            walk(c, path)
        for g in group.get("groups", []):
            walk(g, [*path, g.get("title", "")][-2:] if path else [g.get("title", "")])

    walk(catalog, [])
    return {
        "framework": "ASD Information Security Manual",
        "version": catalog["metadata"].get("version"),
        "baseline": "OFFICIAL: Sensitive",
        "controls": dict(sorted(controls.items())),
    }


def write(name: str, data: dict) -> None:
    text = HEADER + yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=120)
    (DATA / name).write_text(text, encoding="utf-8")
    count = len(data.get("techniques") or data.get("controls"))
    print(f"{name}: {data['framework']} {data['version']}, {count} entries")


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--attack", type=Path, help="enterprise-attack.json (STIX 2.1 bundle)")
    p.add_argument("--atlas", type=Path, help="ATLAS.yaml from mitre-atlas/atlas-data dist/")
    p.add_argument("--ism", type=Path, help="folder holding the ISM OSCAL release")
    args = p.parse_args()
    if args.attack:
        write("attack.yaml", attack(args.attack))
    if args.atlas:
        write("atlas.yaml", atlas(args.atlas))
    if args.ism:
        write("ism.yaml", ism(args.ism))


if __name__ == "__main__":
    main()
